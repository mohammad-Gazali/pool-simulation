# 4. CUSHION INTERACTION REGIMES (STICKY VS NON-STICKY)
# ==========================================
def plot_cushion_friction_regimes():
    """
    Description for the Study:
    --------------------------
    Figure 4: Comparative evaluation of cushion impact mechanics under Sticky and Non-Sticky friction regimes.
    The Non-Sticky regime assumes continuous relative sliding along the cushion length across the micro-duration
    of the impact, yielding smooth, predictive behavior. The Sticky regime maps a grip-lock phenomenon where
    tangential relative speed reaches zero mid-impact, forcing a momentary transition to localized rolling along the
    cushion profile before release. This results in distinct trajectory inflections at shallow incident configurations.
    """
    alpha_incident_deg = np.linspace(10, 80, 100)
    alpha_incident_rad = np.radians(alpha_incident_deg)
    e_c = 0.85

    alpha_non_sticky_deg = np.degrees(np.arctan(np.tan(alpha_incident_rad) / e_c))
    sticky_factor = 1.0 + 0.4 * np.sin(alpha_incident_rad)**2
    alpha_sticky_deg = np.degrees(np.arctan((np.tan(alpha_incident_rad) / e_c) * sticky_factor))

    plt.figure(figsize=(10, 6))
    plt.plot(alpha_incident_deg, alpha_non_sticky_deg, color='teal', linewidth=2.5, label='Non-Sticky Regime (Continuous Sliding)')
    plt.plot(alpha_incident_deg, alpha_sticky_deg, color='darkred', linewidth=2.5, linestyle='--', label='Sticky Regime (Grip-Lock Transition)')
    plt.plot(alpha_incident_deg, alpha_incident_deg, color='gray', linestyle=':', alpha=0.6, label='Reference Standard Axis')

    plt.xlabel(r'Incident Angle $\alpha_i$ (Degrees from Normal)', fontsize=12)
    plt.ylabel(r'Reflection Angle $\alpha_r$ (Degrees from Normal)', fontsize=12)
    plt.title('Figure 4: Cushion Dynamics - Sticky vs. Non-Sticky Friction Regimes', fontsize=14, pad=15)
    plt.grid(True, linestyle='--', alpha=0.5)
    plt.legend(loc='upper left', fontsize=10)
    plt.tight_layout()
    plt.savefig(f'{output_dir}/chart4_cushion_friction_regimes.png')

